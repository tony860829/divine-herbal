  constructor() {
    this.isBrowser = isPlatformBrowser(this.platformId);

    if (this.isBrowser) {
      const saved = localStorage.getItem('pck-lang') as Lang | null;
      if (saved && this.dict[saved]) {
        this.currentLang.set(saved);
      }
    }
  }

  setLang(lang: Lang) {
    this.currentLang.set(lang);
    if (this.isBrowser) {
      localStorage.setItem('pck-lang', lang);
    }
  }

  t(key: string) {
    return computed(() => this.dict[this.currentLang()][key] ?? key);
  }
